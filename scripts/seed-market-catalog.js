async function seedMarketCatalog() {
  console.log(`Starting to seed ${CATALOG_DATA.length} market categories with 5 products each...`);
  let totalCategories = 0;
  let totalProducts = 0;

  for (const item of CATALOG_DATA) {
    const { category, products } = item;

    // Upsert Category
    const catRecord = await prisma.productCategory.upsert({
      where: { slugFa: category.slugFa },
      update: {
        nameFa: category.nameFa,
        nameEn: category.nameEn,
        slugEn: category.slugEn,
        descriptionFa: category.descriptionFa,
        descriptionEn: category.descriptionEn,
        sortOrder: category.sortOrder,
        isActive: true,
      },
      create: {
        nameFa: category.nameFa,
        nameEn: category.nameEn,
        slugFa: category.slugFa,
        slugEn: category.slugEn,
        descriptionFa: category.descriptionFa,
        descriptionEn: category.descriptionEn,
        sortOrder: category.sortOrder,
        isActive: true,
      },
    });

    totalCategories++;
    console.log(`[Category ${totalCategories}/20] Upserted: ${catRecord.nameFa} (${catRecord.id})`);

    // Upsert each of the 5 products for this category
    for (const prod of products) {
      const prodRecord = await prisma.product.upsert({
        where: { slugFa: prod.slugFa },
        update: {
          categoryId: catRecord.id,
          nameFa: prod.nameFa,
          nameEn: prod.nameEn,
          slugEn: prod.slugEn,
          sku: prod.sku,
          price: prod.price,
          stockStatus: 'IN_STOCK',
          shortDescFa: prod.shortDescFa,
          shortDescEn: prod.shortDescEn,
          isActive: true,
        },
        create: {
          categoryId: catRecord.id,
          nameFa: prod.nameFa,
          nameEn: prod.nameEn,
          slugFa: prod.slugFa,
          slugEn: prod.slugEn,
          sku: prod.sku,
          price: prod.price,
          stockStatus: 'IN_STOCK',
          shortDescFa: prod.shortDescFa,
          shortDescEn: prod.shortDescEn,
          isActive: true,
        },
      });

      totalProducts++;
      console.log(`  └─ [Product ${totalProducts}] ${prodRecord.nameFa} -> ${prodRecord.price.toLocaleString('fa-IR')} تومان`);
    }
  }

  console.log(`\n==============================================`);
  console.log(`✅ SEEDING COMPLETE!`);
  console.log(`Total Categories Created/Updated: ${totalCategories}`);
  console.log(`Total Products Created/Updated: ${totalProducts}`);
  console.log(`==============================================\n`);
}

seedMarketCatalog()
  .catch((e) => {
    console.error('Error during catalog seeding:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
