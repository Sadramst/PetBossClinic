async function main() {
  let created = 0
  for (const [i, d] of DRAFTS.entries()) {
    if (await prisma.post.findUnique({ where: { slugFa: d.slug } })) continue
    const category =
      (await prisma.postCategory.findUnique({ where: { slugFa: d.categorySlug } })) ??
      (await prisma.postCategory.create({ data: { slugFa: d.categorySlug, nameFa: d.category, sortOrder: i } }))
    await prisma.post.create({
      data: {
        slugFa: d.slug,
        titleFa: d.title,
        excerptFa: d.excerpt,
        contentFa: d.content,
        focusKeyword: d.focus || null,
        categoryId: category.id,
        readingTime: Math.max(1, Math.round(d.content.split(/\s+/).length / 200)),
        imageId: '/images/veterinarian.jpg',
        isActive: true,
        publishedAt: null, // draft: a vet reviews and publishes it
      },
    })
    created++
  }
  console.log(`Created ${created} draft article(s).`)
}

main()
  .catch((e) => {
    console.error(e)
    process.exitCode = 1
  })
  .finally(() => prisma.$disconnect())
